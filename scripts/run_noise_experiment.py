def format_table(sweep_result: dict, title: str) -> str:
    lines = [
        f"### {title}",
        "",
        "| Noise $\\sigma$ (gray) | Stage 1: Raw Detection | Stage 2: Min-Area Only | Stage 3: Morph + Area | Stage 4: Final Defects | Precision (Stage 4) | Recall (Stage 4) |",
        "| :---: | :---: | :---: | :---: | :---: | :---: | :---: |",
    ]

    for pt in sweep_result["series"]:
        sigma = pt["noise_level"]
        c1 = pt["cases"][0]
        c2 = pt["cases"][1]
        c3 = pt["cases"][2]
        c4 = pt["cases"][3]

        c1_str = f"{c1['mean_count']:.1f} ± {c1['std_count']:.1f}"
        c2_str = f"{c2['mean_count']:.1f} ± {c2['std_count']:.1f}"
        c3_str = f"{c3['mean_count']:.1f} ± {c3['std_count']:.1f}"
        c4_str = f"{c4['mean_count']:.1f} ± {c4['std_count']:.1f}"
        p4_str = f"{c4['mean_precision'] * 100.0:.1f}%"
        r4_str = f"{c4['mean_recall'] * 100.0:.1f}%"

        lines.append(
            f"| {sigma:.1f} | {c1_str} | {c2_str} | {c3_str} | {c4_str} | {p4_str} | {r4_str} |"
        )

    lines.append("")
    lines.append(f"**Stage-by-stage candidate progression across noise levels:**")
    lines.append("")
    lines.append("| Noise $\\sigma$ | Stage | Mean Candidates | TP | FP | FN | Precision | Recall |")
    lines.append("| :---: | :--- | :---: | :---: | :---: | :---: | :---: | :---: |")

    for pt in sweep_result["series"]:
        sigma = pt["noise_level"]
        for case in pt["cases"]:
            lines.append(
                f"| {sigma:.1f} | {case['label']} | {case['mean_count']:.1f} ± {case['std_count']:.1f} | "
                f"{case['mean_tp']:.1f} | {case['mean_fp']:.1f} | {case['mean_fn']:.1f} | "
                f"{case['mean_precision'] * 100.0:.1f}% | {case['mean_recall'] * 100.0:.1f}% |"
            )

    lines.append("")
    return "\n".join(lines)


